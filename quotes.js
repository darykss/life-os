function quoteOfDay(dateStr) {
  const [y, m, d] = dateStr.split('-').map(Number);
  const day = Math.round(Date.UTC(y, m - 1, d) / 864e5);
  const n = QUOTES.length;
  const gcd = (a, b) => (b ? gcd(b, a % b) : a);
  const step = [37, 31, 29, 23, 19, 17, 13, 11, 7, 1].find((s) => gcd(s, n) === 1);
  const q = QUOTES[((day * step) % n + n) % n];
  return { text: q[0], author: q[1] };
}
